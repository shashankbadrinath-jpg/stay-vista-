import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
const url = process.argv[2] || process.env.MCP_URL;
const c = new Client({ name: 'test', version: '1' });
await c.connect(new StreamableHTTPClientTransport(new URL(url)));
const call = async (name, args = {}) => { const r = await c.callTool({ name, arguments: args }); const t = r.content[0].text; return r.isError ? { error: t } : JSON.parse(t); };
console.log('tools:', (await c.listTools()).tools.map((t) => t.name).join(', '));
const lp = await call('list_properties'); console.log('today', lp.server_today, 'props', lp.properties.length);
const add = (d, n) => new Date(Date.parse(d) + n * 864e5).toISOString().slice(0, 10);
const ci = add(lp.server_today, 20), co = add(lp.server_today, 23);
const av = await call('check_availability', { check_in: ci, check_out: co, guests: 6, location: 'coorg' }); console.log('avail', av.map((a) => `${a.unit}:${a.total}`));
const h = await call('hold_dates', { unit_id: av[0].unit_id, check_in: ci, check_out: co, guests: 6, guest_name: 'Priya Test', guest_phone: '919845012345', quote_message: 'Hi Priya, Mantra Villa is held for you.' });
console.log('hold', h.id, h.status, h.guest_link);
console.log('clash', await call('hold_dates', { unit_id: av[0].unit_id, check_in: ci, check_out: co, guests: 6, guest_name: 'X', quote_message: 'x' }));
console.log('confirm', (await call('confirm_booking', { booking_id: h.id })).status);
console.log('summary', JSON.stringify(await call('sales_summary', {})));
console.log('cancel', (await call('cancel_booking', { booking_id: h.id })).status);
const np = await call('add_property', { name: 'Cedar Nest', location: 'Wayanad', units: [{ name: 'Cottage A', capacity: 4, price_per_night: 6500 }] }); console.log('added', np.name, np.units.length);
await c.close();
